"""Evaluation: run every sample log through the analysis and compare with the expected result.

Run from backend/:  ./venv/Scripts/python scripts/evaluate.py
Writes the results table to docs/EVALUATION.md and prints it.

"Correct" means: an incident with the expected category was found
(or, for the healthy file, no incident was found at all).
If LLM_API_KEY is set in .env, the top incident is also sent to the LLM and we
record whether its root cause agrees with the rules (the confidence badge).
"""
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.analysis import config as analysis_config  # noqa: E402
from app.services import analysis_adapter  # noqa: E402
from app.services.grouping import add_templates, group_entries  # noqa: E402
from app.services.incident_builder import build_incidents  # noqa: E402
from app.services.parser import parse_log  # noqa: E402
from app.services.pipeline import entry_dict, incident_context  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SAMPLES = ROOT / "sample_logs"
OUTPUT = ROOT / "docs" / "EVALUATION.md"


def analyze_file(path: Path):
    entries = parse_log(path.read_text(encoding="utf-8")).entries
    add_templates(entries)
    groups = group_entries(entries)
    anomalies = analysis_adapter.detect_anomalies([entry_dict(e) for e in entries], [g.as_dict() for g in groups])
    return entries, build_incidents(entries, anomalies)


def main():
    expected_rows = json.loads((SAMPLES / "expected_results.json").read_text(encoding="utf-8"))
    use_llm = bool(analysis_config.LLM_API_KEY)
    lines = [
        "# Evaluation results",
        "",
        "Generated by `backend/scripts/evaluate.py`. Correct = an incident with the expected category was found "
        "(for the healthy file: no incident at all).",
        "",
        "| File | Seeded failure | Expected | Detected (most severe first) | Incidents expected / found | Correct | LLM root cause / confidence |",
        "|---|---|---|---|---|---|---|",
    ]
    correct = 0
    for row in expected_rows:
        entries, incidents = analyze_file(SAMPLES / row["file"])
        categories = [i.category for i in incidents]
        if row["expected_category"] is None:
            ok = not incidents
        else:
            ok = row["expected_category"] in categories
        correct += ok

        llm_note = "not run (no API key)"
        if use_llm and incidents:
            match = next((i for i in incidents if i.category == row["expected_category"]), incidents[0])
            context = incident_context(match, entries)
            analysis = analysis_adapter.analyze_incident(context, True)
            badge = analysis_adapter.decide_confidence(context, analysis)
            llm_note = f"{analysis['source']}, {badge}: {analysis['root_cause'][:120]}".replace("|", "/")

        lines.append(
            f"| {row['file']} | {row['seeded_failure']} | {row['expected_category'] or 'no incident'} | "
            f"{', '.join(categories) or 'no incident'} | {row['expected_incidents']} / {len(incidents)} | "
            f"{'yes' if ok else 'no'} | {llm_note} |"
        )

    lines += [
        "", f"**Score: {correct} / {len(expected_rows)} files correct.**", "",
        "## Findings", "",
        "- The detectors found the seeded failure in every synthetic file and raised nothing on the healthy file.",
        "- `notification_bad_config.log` is only caught by the first-time-error detector: the errors are minutes "
        "apart, so they are neither a burst nor a spike.",
        "- The real Hadoop slice is detected as an incident, but the keyword rules label it `application`: "
        "Hadoop says \"ERROR IN CONTACTING RM\" and \"NoRouteToHostException\", which are not in the network "
        "keyword list. Adding `noroute`/`no route to host` to the network keywords (backend's incident builder) "
        "would fix it. With an API key, the LLM reads the actual lines and can still name the network cause; "
        "the confidence badge then shows \"low\" because rules and LLM disagree, which is exactly the case it is for.",
        "",
    ]
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
